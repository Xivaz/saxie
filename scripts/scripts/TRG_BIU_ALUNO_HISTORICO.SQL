CREATE OR REPLACE TRIGGER TRG_BIU_ALUNO_HISTORICO BEFORE
  INSERT or UPDATE ON TBL_ALUNO_CURSO_HISTORICO FOR EACH ROW
DECLARE
  PROCEDURE PC_CARGA_HORARIA(PI_DISC_IN_ID INTEGER, PI_CURR_IN_ID INTEGER, PO_CH_TEORICA OUT NUMBER, PO_CH_PRATICA OUT NUMBER) IS
  W_CH_TEORICA TBL_GRADE.GRD_IN_CARGA_HORARIA%TYPE;
  W_CH_PRATICA TBL_GRADE.GRD_IN_CARGA_HRPRATICA%TYPE;
  BEGIN
    IF PI_CURR_IN_ID IS NOT NULL THEN
    SELECT GRD_IN_CARGA_HORARIA, GRD_IN_CARGA_HRPRATICA
	  INTO W_CH_TEORICA, W_CH_PRATICA
	  FROM TBL_GRADE
	 WHERE DISC_IN_ID = PI_DISC_IN_ID
	   AND CURR_IN_ID = PI_CURR_IN_ID;
	ELSE
    SELECT DISC_IN_CARGA_HORARIA, DISC_IN_CARGA_HRPRATICA
	  INTO W_CH_TEORICA, W_CH_PRATICA
	  FROM TBL_DISCIPLINA
	 WHERE DISC_IN_ID = PI_DISC_IN_ID;
	END IF;
	PO_CH_TEORICA := W_CH_TEORICA;
	PO_CH_PRATICA := W_CH_PRATICA;
  END;  
  FUNCTION FC_CALCULA_MEDIA(PI_ACUR_IN_ID INTEGER, W_AV1 NUMBER, W_AV2 NUMBER, W_AV3 NUMBER, W_AV4 NUMBER, W_AV5 NUMBER, W_AV6 NUMBER) RETURN NUMBER IS
    
	TYPE T_REFCURSOR IS REF CURSOR;
    C_REF T_REFCURSOR;
    W_SQL TBL_FORMULA_MEDIA.FMED_ST_CALCULO%TYPE;
    W_CONTAV NUMBER := 0;
    W_RESULT NUMBER := 0;
	W_FMED_ST_CALCULO TBL_FORMULA_MEDIA.FMED_ST_CALCULO%TYPE;
	W_CUR_IN_ID TBL_CURSO.CUR_IN_ID%TYPE;
	W_CUR_IN_MODALIDADE TBL_CURSO.CUR_IN_MODALIDADE%TYPE;
	CURSOR C_CUR IS
	SELECT CUR_IN_ID, CUR_IN_MODALIDADE FROM TBL_CURSO
	 WHERE CUR_IN_ID IN (SELECT CUR_IN_ID FROM TBL_ALUNO_CURSO
	                      WHERE ACUR_IN_ID = PI_ACUR_IN_ID);

  BEGIN
    OPEN C_CUR;
	FETCH C_CUR INTO W_CUR_IN_ID, W_CUR_IN_MODALIDADE;
	CLOSE C_CUR;
	
	BEGIN
	-- Verifica se existe formula para o curso
    SELECT FMED_ST_CALCULO INTO W_FMED_ST_CALCULO
      FROM TBL_FORMULA_MEDIA
     WHERE CUR_IN_ID = W_CUR_IN_ID
       AND FMED_IN_TIPO_DISCIPLINA IS NULL
	   AND ROWNUM =1;
	EXCEPTION WHEN NO_DATA_FOUND THEN
		-- Verifica se existe formula para a modalidade
        SELECT FMED_ST_CALCULO INTO W_FMED_ST_CALCULO
          FROM TBL_FORMULA_MEDIA
         WHERE FMED_IN_MODALIDADE = W_CUR_IN_MODALIDADE       
		   AND FMED_IN_TIPO_DISCIPLINA IS NULL;
	END;
    
    W_SQL := 'SELECT '||REPLACE(W_FMED_ST_CALCULO,'%','*(1/100)')||' FROM DUAL';
    IF INSTR(W_FMED_ST_CALCULO,':AV1')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF INSTR(W_FMED_ST_CALCULO,':AV2')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF INSTR(W_FMED_ST_CALCULO,':AV3')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF INSTR(W_FMED_ST_CALCULO,':AV4')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF INSTR(W_FMED_ST_CALCULO,':AV5')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF INSTR(W_FMED_ST_CALCULO,':AV6')>0 THEN
      W_CONTAV := W_CONTAV + 1;
    END IF;
    IF W_CONTAV = 1 THEN
      OPEN C_REF FOR W_SQL USING W_AV1;
      FETCH C_REF INTO W_RESULT;
      CLOSE C_REF;
    ELSIF W_CONTAV = 2 THEN
      OPEN C_REF FOR W_SQL USING W_AV1, W_AV2;
      FETCH C_REF INTO W_RESULT;
      CLOSE C_REF;
    ELSIF W_CONTAV = 3 THEN
     OPEN C_REF FOR W_SQL USING W_AV1, W_AV2, W_AV3;
     FETCH C_REF INTO W_RESULT;
     CLOSE C_REF;
  ELSIF W_CONTAV = 4 THEN
     OPEN C_REF FOR W_SQL USING W_AV1, W_AV2, W_AV3, W_AV4;
     FETCH C_REF INTO W_RESULT;
     CLOSE C_REF;
  ELSIF W_CONTAV = 5 THEN
     OPEN C_REF FOR W_SQL USING W_AV1, W_AV2, W_AV3, W_AV4, W_AV5;
     FETCH C_REF INTO W_RESULT;
     CLOSE C_REF;
  ELSIF W_CONTAV = 6 THEN
     OPEN C_REF FOR W_SQL USING W_AV1, W_AV2, W_AV3, W_AV4, W_AV5, W_AV6;
     FETCH C_REF INTO W_RESULT;
     CLOSE C_REF;
  END IF;
  
  return W_RESULT;

  EXCEPTION  WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20002,'Erro ao validar a fórmula');

  END;
  -- Calculo da Média Quando Tiver que aplicar a regra definida por Tipo de Disciplina.
  FUNCTION FC_CALCULA_MEDIA_TIPODISC(PI_ACUR_IN_ID INTEGER, PI_DISC_IN_ID INTEGER, W_CURR_IN_ID NUMBER, W_PERI_IN_ID NUMBER, PI_NU_CARGA_HRTEORICA NUMBER, PI_NU_CARGA_HRPRATICA NUMBER, PI_IN_SITUACAO INTEGER) RETURN INTEGER IS
    
	TYPE T_REFCURSOR IS REF CURSOR;
    C_REF T_REFCURSOR;
    W_SQL TBL_FORMULA_MEDIA.FMED_ST_CALCULO%TYPE;
    W_SQL2 TBL_FORMULA_MEDIA.FMED_ST_CALCULO%TYPE;
    W_RESULT INTEGER := 0;
    W_RESULT_A NUMBER := 0;
    W_RESULT_B NUMBER := 0;
	W_FMED_ST_CALCULO TBL_FORMULA_MEDIA.FMED_ST_CALCULO%TYPE;
	W_DIS_IN_TIPO TBL_DISCIPLINA.DIS_IN_TIPO%TYPE;
	W_OPERADORLOGICO VARCHAR2(2) := NULL;
	W_VALORCOMPARADO VARCHAR2(25);
	CURSOR C_DIS_TIPO_FORMULA IS
    SELECT D.DIS_IN_TIPO, F.FMED_ST_CALCULO
      FROM TBL_DISCIPLINA D, TBL_FORMULA_MEDIA F
	 WHERE F.FMED_IN_TIPO_DISCIPLINA = D.DIS_IN_TIPO
	   AND D.DISC_IN_ID = PI_DISC_IN_ID
	   AND F.FMED_IN_TIPO_DISCIPLINA IS NOT NULL;

  BEGIN
  
    OPEN C_DIS_TIPO_FORMULA;
	FETCH C_DIS_TIPO_FORMULA INTO W_DIS_IN_TIPO, W_FMED_ST_CALCULO;
	IF C_DIS_TIPO_FORMULA%NOTFOUND THEN
		RETURN NULL;
	END IF;
	CLOSE C_DIS_TIPO_FORMULA;
	
    W_SQL := 'SELECT '||REPLACE(W_FMED_ST_CALCULO,'%','*(1/100)')||' FROM DUAL';
	
	IF INSTR(W_SQL,'>',1) > 0 THEN
		W_OPERADORLOGICO := SUBSTR(W_SQL,INSTR(W_SQL,'>',1),2);
		DBMS_OUTPUT.PUT_LINE('OPERADOR_LOGICO='||W_OPERADORLOGICO);
		IF W_OPERADORLOGICO IS NOT NULL THEN
			IF SUBSTR(W_OPERADORLOGICO,2)='=' THEN /* >= */ 
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'>')+2);
			ELSE
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'>')+1);
				W_OPERADORLOGICO := '>';
			END IF;
		END IF;
		DBMS_OUTPUT.PUT_LINE('VALOR COMPARADO='||W_VALORCOMPARADO);
	ELSIF INSTR(W_SQL,'<',1) > 0 THEN
		W_OPERADORLOGICO := SUBSTR(W_SQL,INSTR(W_SQL,'<',1),2);
		IF W_OPERADORLOGICO IS NOT NULL THEN
			IF SUBSTR(W_OPERADORLOGICO,2)='=' THEN /* <= */ 
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'<')+2);
			ELSE
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'<')+1);
				W_OPERADORLOGICO := '<';
			END IF;
		END IF;
	ELSIF INSTR(W_SQL,'!',1) > 0 THEN
		W_OPERADORLOGICO := SUBSTR(W_SQL,INSTR(W_SQL,'!',1),2);
		IF W_OPERADORLOGICO IS NOT NULL THEN
			IF SUBSTR(W_OPERADORLOGICO,2)='=' THEN /* != */ 
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'!')+2);
			END IF;
		ELSE
			IF SUBSTR(W_OPERADORLOGICO,1)='=' THEN /* = */ 
				W_VALORCOMPARADO := SUBSTR(W_SQL,INSTR(W_SQL,'=')+1);
				W_OPERADORLOGICO := '=';
			END IF;
		END IF;
	END IF;
		
	W_SQL2 := 'SELECT '|| W_VALORCOMPARADO;
	DBMS_OUTPUT.PUT_LINE(W_SQL2);

    W_SQL  := SUBSTR(W_SQL, 1 , (INSTR(W_SQL,W_OPERADORLOGICO,1)-1)) || ' FROM DUAL';
	DBMS_OUTPUT.PUT_LINE(W_SQL);
	DBMS_OUTPUT.PUT_LINE('PI_ACUR_IN_ID=>'||PI_ACUR_IN_ID);
	DBMS_OUTPUT.PUT_LINE('W_CURR_IN_ID=>' ||W_CURR_IN_ID);
	DBMS_OUTPUT.PUT_LINE('PI_DISC_IN_ID=>'||PI_DISC_IN_ID);
	DBMS_OUTPUT.PUT_LINE('W_PERI_IN_ID=>' ||W_PERI_IN_ID);

    OPEN C_REF FOR W_SQL2;
    FETCH C_REF INTO W_RESULT_B;
    CLOSE C_REF;

    OPEN C_REF FOR W_SQL USING PI_ACUR_IN_ID, W_CURR_IN_ID, PI_DISC_IN_ID, W_PERI_IN_ID, PI_NU_CARGA_HRTEORICA, PI_NU_CARGA_HRPRATICA, PI_IN_SITUACAO, W_CURR_IN_ID, PI_DISC_IN_ID;
    FETCH C_REF INTO W_RESULT_A;
    CLOSE C_REF;
	
	IF W_OPERADORLOGICO = '>' THEN
		IF W_RESULT_A > W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	ELSIF W_OPERADORLOGICO = '>=' THEN
		IF W_RESULT_A >= W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	ELSIF W_OPERADORLOGICO = '<' THEN
		IF W_RESULT_A < W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	ELSIF W_OPERADORLOGICO = '<=' THEN
		IF W_RESULT_A <= W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	ELSIF W_OPERADORLOGICO = '!=' THEN
		IF W_RESULT_A != W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	ELSIF W_OPERADORLOGICO = '=' THEN
		IF W_RESULT_A = W_RESULT_B THEN
			W_RESULT := 1;
		ELSE
			W_RESULT := 0;
		END IF;
	END IF;
  return W_RESULT;

  EXCEPTION  WHEN OTHERS THEN 
  	DBMS_OUTPUT.PUT_LINE('SQL1=>'||W_SQL2);
	DBMS_OUTPUT.PUT_LINE('SQL2=>'||W_SQL);

	RAISE_APPLICATION_ERROR(-20002,'Erro ao validar a fórmula: '||SQLERRM||'('||W_RESULT_A||')('||W_RESULT_B||')');

  END;
  
BEGIN 
  PC_ATUALIZA_USUARIO(:NEW.USER_ST_ATUALIZA,:NEW.USER_DT_ATUALIZA);
  DBMS_OUTPUT.PUT_LINE('PASSOU ATUALIZA USUARIO');
  IF UPDATING THEN
	-- Verifica se fará Cálculo de Regra de Atividades Práticas
	DBMS_OUTPUT.PUT_LINE('UPDATE');
	IF FC_CALCULA_MEDIA_TIPODISC(:OLD.ACUR_IN_ID, :OLD.DISC_IN_ID, :OLD.CURR_IN_ID, :OLD.PERI_IN_ID, :OLD.ACHIS_NU_CHTEORICA_CUMPRIDA, :OLD.ACHIS_NU_CHPRATICA_CUMPRIDA, :OLD.ACHIS_IN_SITUACAO) IS NOT NULL THEN
		DBMS_OUTPUT.PUT_LINE('REGRA POR TIPO DE DISCIPLINA');
		:NEW.ACHIS_IN_SITUACAO_PRATICA := FC_CALCULA_MEDIA_TIPODISC(:OLD.ACUR_IN_ID, :OLD.DISC_IN_ID, :OLD.CURR_IN_ID, :OLD.PERI_IN_ID, :OLD.ACHIS_NU_CHTEORICA_CUMPRIDA, :OLD.ACHIS_NU_CHPRATICA_CUMPRIDA, :OLD.ACHIS_IN_SITUACAO);
		DBMS_OUTPUT.PUT_LINE('SETOU SITUACAO PRATICA');
	ELSE
	-- Verificaa outras regras de calculo
		IF (:NEW.ACHIS_NU_AVAL1 <> :OLD.ACHIS_NU_AVAL1 OR :NEW.ACHIS_NU_AVAL2 <> :OLD.ACHIS_NU_AVAL2 OR
			:NEW.ACHIS_NU_AVAL3 <> :OLD.ACHIS_NU_AVAL3 OR :NEW.ACHIS_NU_AVAL4 <> :OLD.ACHIS_NU_AVAL4 OR
			:NEW.ACHIS_NU_AVAL5 <> :OLD.ACHIS_NU_AVAL5 OR :NEW.ACHIS_NU_AVAL6 <> :OLD.ACHIS_NU_AVAL6) THEN
			:NEW.ACHIS_NU_MEDIA := FC_CALCULA_MEDIA(:NEW.ACUR_IN_ID,:NEW.ACHIS_NU_AVAL1,:NEW.ACHIS_NU_AVAL2,:NEW.ACHIS_NU_AVAL3,:NEW.ACHIS_NU_AVAL4,:NEW.ACHIS_NU_AVAL5,:NEW.ACHIS_NU_AVAL6);
			IF :NEW.ACHIS_NU_MEDIA >= 6 THEN
				:NEW.ACHIS_IN_SITUACAO := 3;
			ELSIF :OLD.ACHIS_IN_SITUACAO <> 5 THEN
				:NEW.ACHIS_IN_SITUACAO := 4;
			END IF;		
		END IF;
	    IF :NEW.ACHIS_IN_SITUACAO <> :OLD.ACHIS_IN_SITUACAO THEN
			IF :NEW.ACHIS_IN_SITUACAO IN (3,5) then -- Aprovado
				DBMS_OUTPUT.PUT_LINE('CHAMOU A CARGA HORARIA');
				PC_CARGA_HORARIA(:NEW.DISC_IN_ID, :NEW.CURR_IN_ID, :NEW.ACHIS_NU_CHTEORICA_CUMPRIDA, :NEW.ACHIS_NU_CHPRATICA_CUMPRIDA);
			END IF;
		END IF;
	END IF;

  ELSE
  		DBMS_OUTPUT.PUT_LINE('INSERT');

	-- Verifica se fará Cálculo de Regra de Atividades Práticas
	IF FC_CALCULA_MEDIA_TIPODISC(:NEW.ACUR_IN_ID, :NEW.DISC_IN_ID, :NEW.CURR_IN_ID, :NEW.PERI_IN_ID, :NEW.ACHIS_NU_CHTEORICA_CUMPRIDA, :NEW.ACHIS_NU_CHPRATICA_CUMPRIDA, :NEW.ACHIS_IN_SITUACAO) IS NOT NULL THEN
		:NEW.ACHIS_IN_SITUACAO_PRATICA := FC_CALCULA_MEDIA_TIPODISC(:NEW.ACUR_IN_ID, :NEW.DISC_IN_ID, :NEW.CURR_IN_ID, :NEW.PERI_IN_ID, :NEW.ACHIS_NU_CHTEORICA_CUMPRIDA, :NEW.ACHIS_NU_CHPRATICA_CUMPRIDA, :NEW.ACHIS_IN_SITUACAO);
	ELSE
	-- Verificaa outras regras de calculo
		IF (:NEW.ACHIS_NU_AVAL1 IS NOT NULL OR :NEW.ACHIS_NU_AVAL2 IS NOT NULL OR
			:NEW.ACHIS_NU_AVAL3 IS NOT NULL OR :NEW.ACHIS_NU_AVAL4 IS NOT NULL OR
			:NEW.ACHIS_NU_AVAL5 IS NOT NULL OR :NEW.ACHIS_NU_AVAL6 IS NOT NULL) THEN
			:NEW.ACHIS_NU_MEDIA := FC_CALCULA_MEDIA(:NEW.ACUR_IN_ID,:NEW.ACHIS_NU_AVAL1,:NEW.ACHIS_NU_AVAL2,:NEW.ACHIS_NU_AVAL3,:NEW.ACHIS_NU_AVAL4,:NEW.ACHIS_NU_AVAL5,:NEW.ACHIS_NU_AVAL6);
			IF :NEW.ACHIS_NU_MEDIA >= 6 THEN
				:NEW.ACHIS_IN_SITUACAO := 3;
			ELSE
				:NEW.ACHIS_IN_SITUACAO := 4;
			END IF;		
		END IF;
		IF :NEW.ACHIS_IN_SITUACAO IN (3,5) then -- Aprovado
			PC_CARGA_HORARIA(:NEW.DISC_IN_ID, :NEW.CURR_IN_ID, :NEW.ACHIS_NU_CHTEORICA_CUMPRIDA, :NEW.ACHIS_NU_CHPRATICA_CUMPRIDA);
		END IF;
	END IF;

  END IF;
END;
