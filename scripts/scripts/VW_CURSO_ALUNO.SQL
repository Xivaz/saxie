CREATE OR REPLACE VIEW VW_CURSO_ALUNO AS
select AC."CUR_IN_ID", 
       AC."ACUR_IN_ID",
       A."ALU_IN_ID",
       C."CUR_ST_NOME",
       A."ALU_ST_NOME",
       A."ALU_IN_RGM",
       A."ALU_ST_NOME_CENSO",
       A."ALU_ST_RG",
       FC_MASCARA_CPF(A."ALU_IN_CPF") "ALU_IN_CPF",
       A."ALU_ST_PASSAPORTE",
       A."ALU_ST_RNE",
       FC_REFERENCIA_DESCRICAO('NACIONALIDADE',A."ALU_IN_NACIONALIDADE") "ALU_ST_NACIONALIDADE",
       TO_CHAR(A."ALU_DT_NASCIMENTO",'DD/MM/YYYY') "ALU_DT_NASCIMENTO",
       FC_REFERENCIA_DESCRICAO('SEXO',A."ALU_IN_SEXO") "ALU_ST_SEXO",
       FC_REFERENCIA_DESCRICAO('COR_RACA',A."ALU_IN_CORRACA") "ALU_ST_COR_RACA",
       A."ALU_ST_NOME_MAE",
       A."ALU_ST_NOME_MAE_CENSO",
       FC_PAIS_NOME(A."ALU_IN_PAIS_ORIGEM") "ALU_ST_PAIS_ORIGEM",
       FC_UF_NOME(A."ALU_IN_UF_NASCIMENTO") "ALU_ST_UF_NASCIMENTO",
       FC_MUNICIPIO_NOME(A."ALU_IN_MUNI_NASCIMENTO") "ALU_ST_MUNI_NASCIMENTO",
       FC_REFERENCIA_DESCRICAO('SIM_NAO',A."ALU_IN_DEFICIENTE") "ALU_ST_DEFICIENTE",
