       FC_REFERENCIA_DESCRICAO('SIM_NAO',A."ALU_IN_CANHOTO") "ALU_ST_CANHOTO",
       FC_REFERENCIA_DESCRICAO('SIM_NAO',A."ALU_IN_OBITO") "ALU_ST_OBITO",
       TO_CHAR(A."ALU_DT_OBITO",'DD/MM/YYYY HH24:MI') "ALU_DT_OBITO", 
	   FC_REFERENCIA_DESCRICAO('TIPO_INGRESSO', AC."ACUR_IN_INGRESSO") "ACUR_ST_INGRESSO",
	   FC_REFERENCIA_DESCRICAO('MOBILIDADE_ACADEMICA', AC."ACUR_IN_MOBDACAD") "ACUR_ST_MOBILIDADE_ACADEMICA",
	   FC_REFERENCIA_DESCRICAO('MOBILIDADE_ACADEMICA', AC."ACUR_IN_MOBDACAD_INTER") "ACUR_ST_MOBILIDADE_INTER",
	   AC."ACUR_IN_MOBDACAD_IESDEST",
	   AC."ACUR_IN_MOBDACAD_PAISDEST",
	   FC_REFERENCIA_DESCRICAO('FINANCIAMENTO_ESTUDANTIL', AC."ACUR_IN_FINANCIAMENTO") "ACUR_ST_FINANCIAMENTO",
	   FC_REFERENCIA_DESCRICAO('APOIO_SOCIAL', AC."ACUR_IN_APOIO_SOCIAL") "ACUR_ST_APOIO_SOCIAL",
	   FC_REFERENCIA_DESCRICAO('ATIVIDADE_EXTRA_CURRICULAR', AC."ACUR_IN_ATIVIDADE_EXTRA") "ACUR_ST_ATIVIDADE_EXTRA",
	   AC."ACUR_NU_BOLSA_PESQUISA",
	   AC."ACUR_NU_BOLSA_EXTENSAO",
	   AC."ACUR_NU_BOLSA_MONITORIA",
	   AC."ACUR_NU_BOLSA_ESTAGIO",
	   AC."ACUR_DT_INGRESSO",
	   AC."ACUR_DT_ULTIMA_MATRICULA",
	   AC."ACUR_DT_COLACAO",
	   AC."ACUR_DT_TRANSFERENCIA",
	   AC."ACUR_DT_EMISSAO_DIPLOMA",
	   FC_REFERENCIA_DESCRICAO('SITUACAO_ALUNO', AC."ACUR_IN_SITUACAO") "ACUR_ST_SITUACAO",
       AC."USER_ST_ATUALIZA",
       TO_CHAR(AC."USER_DT_ATUALIZA",'DD/MM/YYYY HH24:MI') "USER_DT_ATUALIZA"
from "TBL_ALUNO" A
INNER JOIN "TBL_ALUNO_CURSO" AC ON AC.ALU_IN_ID = A.ALU_IN_ID
INNER JOIN "TBL_CURSO" C        ON C.CUR_IN_ID  = AC.CUR_IN_ID; 

GRANT SELECT ON VW_CURSO_ALUNO TO PUBLIC;